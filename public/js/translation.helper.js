/**
 * Translates a single text string to natural Indonesian while strictly
 * preserving proper nouns, feature names, package names, files, and code.
 */
export function translateTextToIndonesian(text) {
  if (!text || typeof text !== 'string') return text;

  const trimmed = text.trim();
  if (!trimmed) return text;

  // 1. Check exact dictionary match
  if (EXACT_TRANSLATIONS[trimmed]) {
    return EXACT_TRANSLATIONS[trimmed];
  }

  // 2. Protect proper nouns and technical entities with tokens
  const placeholders = [];
  let tokenized = text;

  // Protect code backticks
  tokenized = tokenized.replace(/`([^`]+)`/g, (match) => {
    const id = `___PROTECTED_BACKTICK_${placeholders.length}___`;
    placeholders.push({ id, original: match });
    return id;
  });

  // Protect proper nouns
  PROTECTED_PROPER_NOUNS.forEach((noun) => {
    const re = new RegExp(`\\b${escapeRegExp(noun)}\\b`, 'g');
    tokenized = tokenized.replace(re, (match) => {
      const id = `___PROTECTED_NOUN_${placeholders.length}___`;
      placeholders.push({ id, original: match });
      return id;
    });
  });

  // 3. Apply phrasal and sentence patterns
  let translated = tokenized;
  TECHNICAL_PHRASE_PATTERNS.forEach(([pattern, replacement]) => {
    translated = translated.replace(pattern, replacement);
  });

  // 4. Restore protected entities
  placeholders.forEach(({ id, original }) => {
    translated = translated.split(id).join(original);
  });

  return translated;
}

function escapeRegExp(string) {
  return string.replace(/[.*+?^${}()|[\]\\]/g, '\\$&');
}

/**
 * Translates an item (string or object with title/description/purpose)
 */
export function translateItemToIndonesian(item) {
  if (!item) return item;
  if (typeof item === 'string') {
    return translateTextToIndonesian(item);
  }
  if (typeof item === 'object') {
    const copy = { ...item };
    // Keep name / title if it matches a proper noun/feature name, translate description / purpose
    if (copy.description) {
      copy.description = translateTextToIndonesian(copy.description);
    }
    if (copy.purpose) {
      copy.purpose = translateTextToIndonesian(copy.purpose);
    }
    if (copy.distinction) {
      copy.distinction = translateTextToIndonesian(copy.distinction);
    }
    if (copy.comparison) {
      copy.comparison = translateTextToIndonesian(copy.comparison);
    }
    return copy;
  }
  return item;
}

